#!/usr/bin/env node
// Generates src/lib/showcase-s1-code.ts: the copy-pasteable code strings for the S1 showcase demos
// (buttons, forms and inputs) straight from the demo sources, so the code shown always matches the render.
// Run after editing src/components/demos/s1-buttons.tsx or s1-forms.tsx:
//   node apps/docs/scripts/gen-showcase-s1-code.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const sources = ["src/components/demos/s1-buttons.tsx", "src/components/demos/s1-forms.tsx"]
const out = path.join(root, "src/lib/showcase-s1-code.ts")

const MODULE_ORDER = (mod) => (mod === "react" ? 0 : mod.startsWith("@phosphor") ? 1 : mod === "@glinui/ui" ? 2 : 3)

function parseImports(text) {
  const map = new Map() // local name -> { spec, mod }
  const re = /import\s+(?:type\s+)?\{([^}]*)\}\s+from\s+"([^"]+)"/g
  let m
  while ((m = re.exec(text))) {
    for (const raw of m[1].split(",")) {
      const spec = raw.trim()
      if (!spec) continue
      const local = spec.includes(" as ") ? spec.split(" as ")[1].trim() : spec
      map.set(local, { spec, mod: m[2] })
    }
  }
  return map
}

function used(name, body) {
  const esc = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
  return new RegExp(`<${esc}[\\s/>]|\\b${esc}[(<]|:\\s*${esc}\\b|\\b${esc}\\.|\\{${esc}\\}`).test(body)
}

const entries = {}
for (const rel of sources) {
  const text = fs.readFileSync(path.join(root, rel), "utf8")
  const imports = parseImports(text)
  const re = /^export function (\w+)\(\) \{\n[\s\S]*?\n\}\n/gm
  let m
  while ((m = re.exec(text))) {
    const [body, name] = m
    const byMod = new Map()
    for (const [local, { spec, mod }] of imports) {
      if (!used(local, body)) continue
      const target = mod.replace("/dist/ssr", "")
      byMod.set(target, [...(byMod.get(target) ?? []), spec])
    }
    const lines = [...byMod.entries()]
      .sort((a, b) => MODULE_ORDER(a[0]) - MODULE_ORDER(b[0]))
      .map(([mod, specs]) => `import { ${[...new Set(specs)].sort().join(", ")} } from "${mod}"`)
    const client = /\buse(State|Effect|Ref)[(<]/.test(body) ? '"use client"\n\n' : ""
    entries[name] = `${client}${lines.join("\n")}\n\n${body.trimEnd()}`
  }
}

const file = `// Generated by scripts/gen-showcase-s1-code.mjs from the s1 demo sources. Do not edit by hand.\nexport const s1Code: Record<string, string> = ${JSON.stringify(entries, null, 2)}\n`
fs.writeFileSync(out, file)
console.log(`wrote ${Object.keys(entries).length} snippets to ${path.relative(process.cwd(), out)}`)
