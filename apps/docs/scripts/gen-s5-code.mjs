// Extracts each `// @demo` block from the S5 showcase demo files into copy-pasteable code strings.
// Run: node scripts/gen-s5-code.mjs
import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const files = ["s5-motion"]
const out = {}

for (const name of files) {
  const src = fs.readFileSync(path.join(root, "src/components/demos", `${name}.tsx`), "utf8")
  const imports = {}
  for (const m of src.matchAll(/import \{([^}]*)\} from "([^"]+)"/g)) {
    const mod = m[2].replace("/dist/ssr", "")
    for (const n of m[1].split(",").map((s) => s.trim()).filter(Boolean)) imports[n] = mod
  }
  const parts = src.split(/^\/\/ @demo\n/m).slice(1)
  for (const part of parts) {
    const body = part.trimEnd()
    const fn = /export function (\w+)/.exec(body)[1]
    const used = new Map()
    for (const id of new Set(body.match(/\b[A-Za-z][A-Za-z0-9]*\b/g))) {
      if (imports[id]) {
        if (!used.has(imports[id])) used.set(imports[id], [])
        used.get(imports[id]).push(id)
      }
    }
    const order = ["react", "@phosphor-icons/react", "@glinui/ui"]
    const lines = [...used.keys()].sort((a, b) => order.indexOf(a) - order.indexOf(b)).map((mod) => {
      const names = used.get(mod).sort()
      const one = `import { ${names.join(", ")} } from "${mod}"`
      return one.length <= 100 ? one : `import {\n${names.map((n) => `  ${n}`).join(",\n")}\n} from "${mod}"`
    })
    out[fn] = `${lines.join("\n")}\n\n${body.replace(`export function ${fn}`, "export function Demo")}\n`
  }
}

const header = "// Generated by scripts/gen-s5-code.mjs from src/components/demos/s5-motion.tsx. Do not edit by hand.\n"
fs.writeFileSync(
  path.join(root, "src/lib/s5-code.generated.ts"),
  `${header}export const s5Code: Record<string, string> = ${JSON.stringify(out, null, 2)}\n`
)
console.log(`wrote ${Object.keys(out).length} snippets`)
